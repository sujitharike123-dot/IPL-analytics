"""Run the IPL analysis: SQL queries (SQLite), statistical tests, figures and a findings file.

Usage (from the repo root, after src/prepare_data.py):
    python src/run_analysis.py

Writes:
    results/sql_results.md   every SQL query result as a table
    results/findings.json    the headline numbers quoted in the README, with confidence intervals and p-values
    figures/*.png            charts for the README
"""
import json
import os
import sqlite3
import sys

import numpy as np
import pandas as pd
from scipy.stats import binomtest, fisher_exact, ttest_ind

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
sys.path.insert(0, ROOT)
import ipl_charts as ch  # noqa: E402
from ipl_utils import HYD, PROC, wilson_ci  # noqa: E402

FIG, RES, SQL = (os.path.join(ROOT, d) for d in ("figures", "results", "sql"))
os.makedirs(FIG, exist_ok=True)
os.makedirs(RES, exist_ok=True)

# ------------------------------------------------------------------ load into SQLite
tables = {"matches": "matches_clean.csv", "innings": "innings_summary.csv",
          "batting": "batting_by_phase.csv", "bowling": "bowling_by_phase.csv"}
con = sqlite3.connect(":memory:")
frames = {}
for name, f in tables.items():
    df = pd.read_csv(os.path.join(PROC, f))
    for c in ["is_dl", "no_result", "decided", "toss_chose_field"]:
        if c in df.columns:
            df[c] = df[c].astype(int)
    if name == "matches":
        df["date"] = df["date"].astype(str)
    frames[name] = df
    df.to_sql(name, con, index=False)
print({k: len(v) for k, v in frames.items()})

# ------------------------------------------------------------------ run the SQL file
with open(os.path.join(SQL, "ipl_queries.sql")) as f:
    blocks = [b.strip() for b in f.read().split("-- QUERY:")[1:] if b.strip()]  # [0] is the file header
Q = {}
for b in blocks:
    title, _, query = b.partition("\n")
    Q[title.strip()] = pd.read_sql_query(query, con)
with open(os.path.join(RES, "sql_results.md"), "w") as f:
    f.write("# SQL results\n\nGenerated by `src/run_analysis.py` from `sql/ipl_queries.sql`.\n\n")
    for title, res in Q.items():
        f.write(f"## {title}\n\n{res.to_markdown(index=False)}\n\n")
print(f"Ran {len(Q)} SQL queries")


def q(prefix):
    for k, v in Q.items():
        if k.startswith(prefix):
            return v
    raise KeyError(prefix)


# ------------------------------------------------------------------ statistics
m = frames["matches"]
inn = frames["innings"]
F = {}  # findings
F["data"] = {"matches": int(len(m)), "deliveries": int(json.load(open(os.path.join(PROC, "data_quality.json")))["raw_deliveries"]),
             "first_season": int(m["year"].min()), "last_season": int(m["year"].max()),
             "decided_matches": int(m["decided"].sum())}


def prop(k, n):
    lo, hi = wilson_ci(k, n)
    return {"wins": int(k), "matches": int(n), "pct": round(100 * k / n, 1), "ci95": [round(lo, 1), round(hi, 1)],
            "p_vs_50": round(binomtest(int(k), int(n), 0.5).pvalue, 4)}


dec = m[m["decided"] == 1]
F["toss"] = {"toss_winner_wins": prop(dec["toss_winner_won"].sum(), len(dec))}
for dcn in ["bat", "field"]:
    s = dec[dec["toss_decision"] == dcn]
    F["toss"][f"chose_{dcn}"] = prop(s["toss_winner_won"].sum(), len(s))

ch_m = m[m["chase_won"].notna()]
F["chase"] = {"all": prop(ch_m["chase_won"].sum(), len(ch_m))}
recent = ch_m[ch_m["year"] >= 2023]
older = ch_m[ch_m["year"] < 2023]
F["chase"]["2023_24"] = prop(recent["chase_won"].sum(), len(recent))
F["chase"]["2008_22"] = prop(older["chase_won"].sum(), len(older))
tbl = [[recent["chase_won"].sum(), len(recent) - recent["chase_won"].sum()],
       [older["chase_won"].sum(), len(older) - older["chase_won"].sum()]]
F["chase"]["recent_vs_older_fisher_p"] = round(float(fisher_exact(tbl)[1]), 3)
F["chase"]["by_season"] = q("Chasing success by season")[["year", "chase_win_pct"]].to_dict("records")
F["toss_decision_field_pct"] = {"2010": float(q("Share of toss winners")["chose_to_field_pct"].iloc[2]),
                                "2022": float(q("Share of toss winners")["chose_to_field_pct"].iloc[14])}

home = m[m["home_team"].notna() & (m["decided"] == 1)]
hw = int((home["winner"] == home["home_team"]).sum())
F["home_advantage"] = prop(hw, len(home))
srh = frames["matches"]
for team in ["Sunrisers Hyderabad", "Deccan Chargers", "Chennai Super Kings", "Rajasthan Royals"]:
    h = srh[(srh["home_team"] == team) & (srh["decided"] == 1)]
    a = srh[(srh["away_team"] == team) & (srh["decided"] == 1)]
    hk, ak = int((h["winner"] == team).sum()), int((a["winner"] == team).sum())
    F.setdefault("team_home_away", {})[team] = {
        "home": prop(hk, len(h)), "away": prop(ak, len(a)),
        "fisher_p": round(float(fisher_exact([[hk, len(h) - hk], [ak, len(a) - ak]])[1]), 3)}

f1 = inn[(inn["inning"] == 1) & (inn["no_result"] == 0) & (inn["is_dl"] == 0)]
new, old = f1[f1["year"] >= 2023]["runs"], f1[f1["year"] < 2023]["runs"]
t = ttest_ind(new, old, equal_var=False)
F["era"] = {"avg_first_innings_2008_22": round(float(old.mean()), 1), "avg_first_innings_2023_24": round(float(new.mean()), 1),
            "innings_2008_22": int(len(old)), "innings_2023_24": int(len(new)),
            "pct_200_plus_2008_22": round(100 * float((old >= 200).mean()), 1),
            "pct_200_plus_2023_24": round(100 * float((new >= 200).mean()), 1),
            "welch_t_p": float(f"{t.pvalue:.2e}")}
F["records"] = q("Ten highest team totals").head(4)[["batting_team", "bowling_team", "runs", "wickets", "year"]].to_dict("records")
F["total_sixes"] = int(inn["sixes"].sum())
F["target_bands"] = q("Chase win rate by target band").to_dict("records")
F["powerplay_vs_win"] = q("Powerplay runs and winning").to_dict("records")
F["venues"] = q("Venue guide").to_dict("records")
F["uppal"] = q("Uppal as a ground").to_dict("records")
F["hyderabad_franchises"] = q("Hyderabad franchises").to_dict("records")
F["franchises"] = q("Franchise table").to_dict("records")
F["top_scorers"] = q("Top run scorers").head(5).to_dict("records")
F["death_bowlers"] = q("Best death-over bowlers").head(5).to_dict("records")
with open(os.path.join(RES, "findings.json"), "w") as f:
    json.dump(F, f, indent=2, default=float)

# ------------------------------------------------------------------ figures
ch.save(ch.chart_chase_by_year(q("Chasing success by season")), os.path.join(FIG, "chase_win_by_season.png"))
ch.save(ch.chart_toss_decision_by_year(q("Share of toss winners")), os.path.join(FIG, "toss_decision_by_season.png"))
rates = q("Runs per over by phase")
ch.save(ch.chart_phase_rates(rates), os.path.join(FIG, "phase_run_rates.png"))
ch.save(ch.chart_avg_first_innings(q("Average first-innings score")), os.path.join(FIG, "avg_first_innings.png"))
ch.save(ch.chart_200_plus(q("200+ totals")), os.path.join(FIG, "scores_200_plus.png"))
ch.save(ch.chart_sixes_per_match(q("200+ totals")), os.path.join(FIG, "sixes_per_match.png"))
ch.save(ch.chart_target_bands(q("Chase win rate by target band")), os.path.join(FIG, "target_bands.png"))
ch.save(ch.chart_powerplay_vs_win(q("Powerplay runs and winning")), os.path.join(FIG, "powerplay_vs_win.png"))
venues = q("Venue guide")
ch.save(ch.chart_venues(venues, highlight=HYD), os.path.join(FIG, "venue_scoring.png"))
ch.save(ch.chart_chase_by_venue(venues, highlight=HYD), os.path.join(FIG, "venue_chasing.png"))
ch.save(ch.chart_home_away(q("Home vs away win rate")), os.path.join(FIG, "home_vs_away.png"))
print("Saved results/sql_results.md, results/findings.json and", len(os.listdir(FIG)), "figures")
print(json.dumps({k: F[k] for k in ["toss", "chase", "home_advantage", "team_home_away", "era"]}, indent=2, default=float))
